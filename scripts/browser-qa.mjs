import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright')
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1512, height: 982 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const url = process.env.PORTFOLIO_URL ?? 'http://127.0.0.1:5173/'
const settle = () => page.waitForTimeout(850)
const jump = async id => { await page.evaluate(id => document.getElementById(id).scrollIntoView({ behavior: 'instant' }), id); await settle() }
const progress = () => page.locator('[role="progressbar"]').getAttribute('aria-valuenow')
try {
  await page.goto(url); await page.evaluate(() => document.fonts.ready)
  assert.equal(await page.locator('main > section').count(), 5)
  await jump('design-cases')
  const design = page.locator('#design-cases')
  assert.equal(await progress(), '60')
  assert.equal(await design.locator('output').textContent(), '1/5')
  await design.getByRole('button', { name: 'Next project' }).click()
  assert.equal(await design.locator('output').textContent(), '2/5')
  assert.equal(await design.getByRole('button', { name: 'Next project' }).evaluate(node => node === document.activeElement), true, 'Carousel controls retain keyboard focus')
  assert.equal(await progress(), '60')
  await design.getByRole('button', { name: 'Next project' }).click()
  assert.equal(await design.locator('output').textContent(), '3/5')
  await design.getByRole('button', { name: 'Next project' }).click()
  await design.getByRole('button', { name: 'Next project' }).click()
  assert.equal(await design.locator('output').textContent(), '5/5')
  assert(await design.getByRole('button', { name: 'Next project' }).isEnabled())
  await design.getByRole('button', { name: 'Next project' }).click()
  assert.equal(await design.locator('output').textContent(), '1/5')
  await design.getByRole('button', { name: 'Previous project' }).click()
  assert.equal(await design.locator('output').textContent(), '5/5')
  await jump('side-quests')
  assert.equal(await page.locator('#side-quests output').textContent(), '1/4')
  await page.locator('#side-quests').getByRole('button', { name: 'Next project' }).click()
  await jump('design-cases'); assert.equal(await design.locator('output').textContent(), '5/5')
  await jump('side-quests'); assert.equal(await page.locator('#side-quests output').textContent(), '2/4')
  await jump('experience'); await page.waitForTimeout(3400)
  const offset = () => page.locator('.constellation-line path').evaluate(p => Number(p.style.strokeDashoffset))
  assert.equal(await offset(), 0)
  await page.getByRole('button', { name: /Read INDUSTRIAL EXPERIENCE/ }).click()
  assert(await page.locator('#experience-note').isVisible())
  await page.getByRole('button', { name: 'Close milestone details' }).click()
  await jump('main'); await jump('experience'); assert.equal(await offset(), 0)
  await page.locator('body').click({ position: { x: 10, y: 120 } }); await page.keyboard.press('End'); await settle(); assert.equal(await progress(), '100')
  await page.keyboard.press('Home'); await settle(); assert.equal(await progress(), '20')
  await page.mouse.move(10, 300)
  for (let index = 0; index < 18; index++) { await page.mouse.wheel(0, 70); await page.waitForTimeout(100) }
  await settle(); assert.equal(await progress(), '40', 'One sustained wheel gesture advances one section')
  for (const width of [320, 375, 390, 430, 768, 1024, 1440, 1512]) {
    await page.setViewportSize({ width, height: width < 1024 ? 844 : 982 }); await page.goto(url); await page.evaluate(() => document.fonts.ready)
    for (const id of ['main', 'experience', 'design-cases', 'side-quests', 'contacts']) {
      await jump(id)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${width}: horizontal overflow in ${id}`)
      await page.locator(`#${id} img`).evaluateAll(images => Promise.all(images.map(image => image.decode().catch(() => {}))))
      const broken = await page.locator(`#${id} img`).evaluateAll(images => images.filter(image => !image.naturalWidth).map(image => image.src))
      assert.deepEqual(broken, [], `${width}: missing assets in ${id}`)
    }
    console.log(`PASS ${width}px: five sections, no page overflow, all used assets loaded`)
  }
  await page.setViewportSize({ width: 390, height: 844 }); await page.goto(url)
  await page.getByRole('button', { name: 'Open navigation' }).click()
  assert(await page.locator('nav.is-open').isVisible())
  await page.keyboard.press('Escape'); assert.equal(await page.locator('nav.is-open').count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Open navigation' }).evaluate(node => node === document.activeElement), true)
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('button', { name: 'EXPERIENCE', exact: true }).click(); await settle()
  assert.equal(await page.locator('nav.is-open').count(), 0); assert.equal(await progress(), '40')
  const early = await offset(); assert(early > 0, 'Mobile timeline starts partially drawn')
  await page.evaluate(() => window.scrollBy({ top: 700, behavior: 'instant' })); await settle()
  const later = await offset(); assert(later < early)
  await page.evaluate(() => window.scrollBy({ top: -500, behavior: 'instant' })); await settle(); assert.equal(await offset(), later)
  await page.emulateMedia({ reducedMotion: 'reduce' }); await settle(); assert.equal(await offset(), 0)
  assert.equal(await page.locator('.selection-cursor').evaluate(node => getComputedStyle(node).display), 'none')
  await page.evaluate(async () => { const fixture = await import('/scripts/carousel-fixtures.tsx'); fixture.renderProjects([]) })
  await page.waitForTimeout(100)
  const fixture = page.locator('#carousel-fixture')
  assert.equal(await fixture.locator('button').count(), 0)
  assert.equal(await fixture.locator('.empty-projects').textContent(), 'Projects will appear here.')
  await page.evaluate(async () => { const fixture = await import('/scripts/carousel-fixtures.tsx'); fixture.renderProjects([{ id: 'one', title: 'One project', category: 'creative-experiment', contributions: [], media: [], presentationVariant: 'creative-showcase' }]) })
  await page.waitForTimeout(100)
  assert.equal(await fixture.locator('output').textContent(), '1/1')
  assert.equal(await fixture.locator('button:disabled').count(), 2)
  assert.equal(await fixture.locator('a').count(), 0)
  assert.equal(await fixture.locator('.media-placeholder').count(), 1)
  await page.evaluate(async () => {
    const fixture = await import('/scripts/carousel-fixtures.tsx')
    const base = { category: 'creative-experiment', contributions: [], presentationVariant: 'game-showcase' }
    fixture.renderProjects([{ ...base, id: 'one', title: 'One project', media: [{ src: '/assets/dju-preview.jpg', alt: 'First image', type: 'image' }, { src: '/assets/43e9b.png', alt: 'Second image', type: 'image' }], externalLink: { label: 'Real link', url: 'https://www.figma.com/' } }, { ...base, id: 'two', title: 'Second project', media: [] }])
  })
  await page.waitForTimeout(100)
  assert.equal(await fixture.locator('output').textContent(), '1/2')
  assert.equal(await fixture.locator('.multiple-media figure').count(), 2)
  await page.evaluate(() => {
    const image = document.querySelector('#carousel-fixture .multiple-media img')
    const start = new Touch({ identifier: 1, target: image, clientX: 250, clientY: 400 })
    const end = new Touch({ identifier: 1, target: image, clientX: 100, clientY: 400 })
    image.dispatchEvent(new TouchEvent('touchstart', { bubbles: true, touches: [start] }))
    image.dispatchEvent(new TouchEvent('touchend', { bubbles: true, changedTouches: [end] }))
  })
  assert.equal(await fixture.locator('output').textContent(), '1/2', 'Media gallery gestures do not change the project')
  assert.equal(await fixture.getByRole('link', { name: /Real link/ }).getAttribute('href'), 'https://www.figma.com/')
  await fixture.getByRole('button', { name: 'Next project' }).click()
  assert.equal(await fixture.locator('h2').textContent(), 'Second project')
  await page.evaluate(async () => { const fixture = await import('/scripts/carousel-fixtures.tsx'); const base = { category: 'creative-experiment', contributions: [], media: [], presentationVariant: 'game-showcase' }; fixture.renderProjects([{ ...base, id: 'two', title: 'Second project' }, { ...base, id: 'one', title: 'One project' }]) })
  await page.waitForTimeout(100)
  assert.equal(await fixture.locator('output').textContent(), '1/2', 'Reordering data preserves the selected project by ID')
  await page.evaluate(async () => {
    const fixture = await import('/scripts/carousel-fixtures.tsx')
    fixture.renderProjects([{ id: 'two', title: 'Preview override', category: 'creative-experiment', presentationVariant: 'game-showcase',
      media: [{ src: '/assets/dju-preview.jpg', alt: 'Full project image', type: 'image' }],
      previewMedia: [{ src: '/assets/43e9b.png', alt: 'Explicit preview image', type: 'image' }] }])
  })
  await fixture.getByAltText('Explicit preview image').waitFor()
  assert.equal(await fixture.locator('.media-gallery figure').count(), 1, 'Explicit preview media takes precedence over project media')
  assert.equal(await fixture.getByAltText('Full project image').count(), 0)
  await page.evaluate(async () => {
    const fixture = await import('/scripts/carousel-fixtures.tsx')
    fixture.renderProjects([{ id: 'two', title: 'Empty preview override', category: 'creative-experiment', presentationVariant: 'game-showcase',
      media: [{ src: '/assets/dju-preview.jpg', alt: 'Full project image', type: 'image' }], previewMedia: [] }])
  })
  await fixture.locator('.media-placeholder').waitFor()
  assert.equal(await fixture.locator('.media-gallery figure').count(), 0, 'An explicit empty preview does not fall back to project media')
  await page.evaluate(async () => { const fixture = await import('/scripts/carousel-fixtures.tsx'); fixture.cleanup() })
  assert.deepEqual(errors, [])
  console.log('PASS navigation, carousel independence/persistence/boundaries/focus, wheel gesture, mobile menu, constellation persistence, reduced motion, empty/single/multiple project data, optional links, media galleries, reordering, and runtime errors')
} finally { await browser.close() }
